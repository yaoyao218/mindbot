def assign_tarot_structured(emotion: str, arousal: int) -> dict:
    """
    依情緒強度指派塔羅牌，回傳結構化 dict。
    arousal 4–5 → 大阿爾克那
    arousal 2–3 → 小阿爾克那（按花色）
    arousal ≤1 或 平靜/釋然 → QUOTES 名言
    """
    calm_emotions = {"平靜", "釋然"}

    # 名言模式
    if arousal <= 1 or emotion in calm_emotions:
        quotes = QUOTES.get(emotion, QUOTES["default"])
        text = random.choice(quotes)
        return {
            "mode": "quote",
            "card_name": None,
            "card_full": None,
            "meaning": text,
            "is_reversed": False,
            "suit": None,
        }

    # 小阿爾克那
    if arousal in (2, 3):
        suit = EMOTION_TO_MINOR_SUIT.get(emotion, "cups")
        candidates = {k: v for k, v in MINOR_ARCANA.items() if k.startswith(suit)}
        key, card = random.choice(list(candidates.items()))
        is_reversed = random.random() < 0.3
        meaning = card["reversed"] if is_reversed else card["upright"]
        return {
            "mode": "minor",
            "card_name": card["name"],
            "card_full": card["name"],
            "meaning": meaning,
            "is_reversed": is_reversed,
            "suit": suit,
        }

    # 大阿爾克那（arousal 4–5）
    pool = EMOTION_TO_TAROT_POOL.get(emotion, list(range(22)))
    card_id = random.choice(pool)
    card = MAJOR_ARCANA.get(card_id, random.choice(list(MAJOR_ARCANA.values())))
    is_reversed = random.random() < 0.3
    meaning = card["reversed"] if is_reversed else card["upright"]
    name = card["name"].split(" ")[0]
    return {
        "mode": "major",
        "card_name": name,
        "card_full": card["name"],
        "meaning": meaning,
        "is_reversed": is_reversed,
        "suit": None,
    }


def assign_milestone_tarot() -> dict:
    """里程碑專用：固定從成長主題牌池選大阿爾克那"""
    card_id = random.choice(MILESTONE_TAROT_POOL)
    card = MAJOR_ARCANA[card_id]
    is_reversed = random.random() < 0.2   # 里程碑偏向正位
    meaning = card["reversed"] if is_reversed else card["upright"]
    name = card["name"].split(" ")[0]
    return {
        "mode": "major",
        "card_name": name,
        "card_full": card["name"],
        "meaning": meaning,
        "is_reversed": is_reversed,
        "suit": None,
    }


def format_tarot_reply(tarot: dict) -> str:
    """將結構化 tarot dict 格式化為 LINE Bot 顯示文字"""
    if tarot["mode"] == "quote":
        return tarot["meaning"]
    pos = "逆位" if tarot["is_reversed"] else "正位"
    return f"【{tarot['card_name']}・{pos}】\n{tarot['meaning']}\n\n今晚就先到這裡。"


def pick_tarot(emotion: str) -> str:
    """根據情緒挑選塔羅牌並生成輸出文字"""
    pool = EMOTION_TO_TAROT_POOL.get(emotion, list(range(22)))
    card_id = random.choice(pool)
    card = MAJOR_ARCANA.get(card_id)
    if not card:
        card = random.choice(list(MAJOR_ARCANA.values()))
        card_id = list(MAJOR_ARCANA.keys())[0]
    # 70% 正位，30% 逆位
    is_upright = random.random() < 0.7
    meaning = card["upright"] if is_upright else card["reversed"]
    name = card["name"].split(" ")[0]  # 取中文名，例：月亮
    return f"【{name}】\n{meaning}\n\n今晚就先到這裡。"


def pick_quote(emotion: str) -> str:
    """根據情緒挑選名言並生成輸出文字"""
    quotes = QUOTES.get(emotion, QUOTES["default"])
    return random.choice(quotes)


def select_symbol(emotion: str, closing_text: Optional[str] = None) -> str:
    """
    選擇象徵系統並生成結尾回應

    emotion: 偵測到的情緒基調
    closing_text: 用戶在結尾邀請中回覆的句子（可為 None）
    """
    mode = EMOTION_TO_SYMBOL.get(emotion, "quote")

    if mode == "tarot":
        return pick_tarot(emotion)
    else:
        return pick_quote(emotion)


def get_complex_emotion_response(emotions: list[str]) -> str:
    """複雜情緒（多種並存）處理"""
    if len(emotions) >= 2:
        e1, e2 = emotions[0], emotions[1]
        return (
            f"你剛才說的裡面，\n"
            f"我好像同時聽到了有點{e1}，也有點{e2}——\n\n"
            f"這兩個，哪一個比較重？"
        )
    return "你現在的感覺很複雜，說不清楚也沒關係。\n哪個部分是最重的？"


def detect_closing_signal(text: str) -> bool:
    """偵測用戶是否出現收尾語"""
    closing_signals = [
        "謝謝", "好多了", "沒事了", "好了", "輕鬆了",
        "清楚了", "說完了", "差不多了", "夠了", "先這樣",
        "感謝", "bye", "掰掰", "晚安", "休息了",
    ]
    return any(sig in text for sig in closing_signals)
